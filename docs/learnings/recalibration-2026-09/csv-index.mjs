#!/usr/bin/env node
// Writes a cell-by-cell index of a CSV so cells can be read and cited as A2, B45, ...
// Usage: node csv-index.mjs <file.csv> [out.md]   (default out: <file>.index.md)
// Re-run after saving the CSV from Excel; save as "CSV UTF-8" so non-ASCII text survives.
import { readFileSync, writeFileSync } from 'node:fs';

const [csvPath, outArg] = process.argv.slice(2);
if (!csvPath) {
  console.error('usage: node csv-index.mjs <file.csv> [out.md]');
  process.exit(2);
}
const outPath = outArg ?? csvPath.replace(/\.csv$/i, '') + '.index.md';

const bytes = readFileSync(csvPath);
const text = new TextDecoder('utf-8').decode(bytes).replace(/^\uFEFF/, '');
if (text.includes('\uFFFD')) {
  console.error(`csv-index: ${csvPath} is not valid UTF-8 (saved as plain "CSV" from Excel?). Re-save as "CSV UTF-8".`);
  process.exit(1);
}

// RFC 4180 parser: quoted fields, doubled quotes, embedded commas and line breaks.
function parse(s) {
  const rows = [];
  let row = [], field = '', quoted = false;
  for (let i = 0; i < s.length; i++) {
    const c = s[i];
    if (quoted) {
      if (c === '"' && s[i + 1] === '"') { field += '"'; i++; }
      else if (c === '"') quoted = false;
      else field += c;
    } else if (c === '"') quoted = true;
    else if (c === ',') { row.push(field); field = ''; }
    else if (c === '\n') { row.push(field); rows.push(row); row = []; field = ''; }
    else if (c !== '\r') field += c;
  }
  if (quoted) throw new Error('unterminated quoted field at end of file');
  if (field !== '' || row.length) { row.push(field); rows.push(row); }
  return rows;
}

const col = (n) => { let s = ''; for (n++; n > 0; n = Math.floor((n - 1) / 26)) s = String.fromCharCode(65 + ((n - 1) % 26)) + s; return s; };

const rows = parse(text);
const header = rows[0] ?? [];
const width = Math.max(...rows.map((r) => r.length));
const out = [`# Cell index: ${csvPath.split(/[\\/]/).pop()}`, '',
  `${rows.length} rows (row 1 is the header), ${width} columns. Generated by csv-index.mjs; do not edit, re-run it.`, '',
  '## Columns', '', ...header.map((h, i) => `- ${col(i)}: ${h}`), ''];

// A group starts wherever the "New rule" column is filled; without that header, column A.
const key = Math.max(0, header.indexOf('New rule'));
let cells = 0, group = 0, currentKey = '';
for (let r = 1; r < rows.length; r++) {
  const row = rows[r], n = r + 1;
  if (row[key]) {
    group++;
    currentKey = `${col(key)}${n}`;
    out.push(`## Group ${group} (starts row ${n})`, '');
  }
  out.push(`### Row ${n}${row[key] ? '' : ` (new rule in ${currentKey})`}`, '');
  for (let c = 0; c < width; c++) {
    const v = row[c] ?? '';
    out.push(`- **${col(c)}${n}**${header[c] ? ` (${header[c]})` : ''}: ${v === '' ? '_empty_' : v}`);
    cells++;
  }
  out.push('');
}

writeFileSync(outPath, out.join('\n'), 'utf8');
console.log(`csv-index: ${rows.length - 1} data rows, ${width} columns, ${cells} cells, ${group} groups -> ${outPath}`);
